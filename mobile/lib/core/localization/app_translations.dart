String _translateDateWords(String source) {
  var result = source;
  const shortMonths = {
    'Oca': 'Jan',
    'Şub': 'Feb',
    'Mar': 'Mar',
    'Nis': 'Apr',
    'May': 'May',
    'Haz': 'Jun',
    'Tem': 'Jul',
    'Ağu': 'Aug',
    'Eyl': 'Sep',
    'Eki': 'Oct',
    'Kas': 'Nov',
    'Ara': 'Dec',
  };
  result = result.replaceAllMapped(
    RegExp(
      r'(\d{1,2}) (Oca|Şub|Mar|Nis|May|Haz|Tem|Ağu|Eyl|Eki|Kas|Ara)(?=\s|$)',
    ),
    (m) => '${m[1]} ${shortMonths[m[2]]}',
  );
  const words = <String, String>{
    'Pazartesi': 'Monday',
    'Çarşamba': 'Wednesday',
    'Perşembe': 'Thursday',
    'Cumartesi': 'Saturday',
    'Haziran': 'June',
    'Temmuz': 'July',
    'Ağustos': 'August',
    'Eylül': 'September',
    'Ekim': 'October',
    'Kasım': 'November',
    'Aralık': 'December',
    'Ocak': 'January',
    'Şubat': 'February',
    'Mart': 'March',
    'Nisan': 'April',
    'Mayıs': 'May',
    'Salı': 'Tuesday',
    'Cuma': 'Friday',
    'Pazar': 'Sunday',
  };
  for (final entry in words.entries) {
    result = result.replaceAll(entry.key, entry.value);
  }
  return result;
}
