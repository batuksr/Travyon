String translateDynamicEnglish(
  String source,
  String Function(String value) translate,
) {
  String? replace(RegExp pattern, String Function(Match match) value) {
    final match = pattern.firstMatch(source);
    return match == null ? null : value(match);
  }

  return replace(
        RegExp(r'^([^·]+) bütçe aşıldı$'),
        (m) => '${m[1]} over budget',
      ) ??
      replace(RegExp(r'^([^·]+) kaldı$'), (m) => '${m[1]} remaining') ??
      replace(
        RegExp(r'^(.+) tahmini toplam$'),
        (m) => '${m[1]} estimated total',
      ) ??
      replace(
        RegExp(r'^Tüm kayıtlar · (\d+)$'),
        (m) => 'All items · ${m[1]}',
      ) ??
      replace(RegExp(r'^“(.+)” silinsin mi\?$'), (m) => 'Delete “${m[1]}”?') ??
      replace(RegExp(r'^(\d+) gün$'), (m) => '${m[1]} days') ??
      replace(
        RegExp(r'^(\d+) / (\d+) tamamlandı$'),
        (m) => '${m[1]} / ${m[2]} completed',
      ) ??
      replace(
        RegExp(r'^(.+) · Tarihler hazır$'),
        (m) => '${translate(m[1]!)} · Dates ready',
      ) ??
      replace(
        RegExp(
          r'^Bildirimler gösteriliyor ancak kapatma tercihin yüklenemedi\. (.+)$',
        ),
        (m) =>
            'Notifications are shown, but your dismissal preferences could not be loaded. ${translate(m[1]!)}',
      ) ??
      replace(
        RegExp(r'^(\d+) / (\d+) madde tamamlandı$'),
        (m) => '${m[1]} / ${m[2]} items completed',
      ) ??
      replace(
        RegExp(r'^(\d+) / (\d+) durağa harcama girildi\.$'),
        (m) => 'Spending added to ${m[1]} / ${m[2]} stops.',
      ) ??
      replace(
        RegExp(r'^(\d+) / (\d+) durak · (.+)$'),
        (m) => '${m[1]} / ${m[2]} stops · ${translate(m[3]!)}',
      ) ??
      replace(
        RegExp(r'^(\d+) gün · (\d+) gece$'),
        (m) => '${m[1]} days · ${m[2]} nights',
      ) ??
      replace(
        RegExp(r'^(\d+) gün · (\d+) kişi$'),
        (m) => '${m[1]} days · ${m[2]} people',
