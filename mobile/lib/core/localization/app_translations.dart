String translateDynamicEnglish(
  String source,
  String Function(String value) translate,
) {
  String? replace(RegExp pattern, String Function(Match match) value) {
    final match = pattern.firstMatch(source);
    return match == null ? null : value(match);
  }

  return replace(
        RegExp(r'^(\d+) / (\d+) madde tamamlandı$'),
        (m) => '${m[1]} / ${m[2]} items completed',
      ) ??
      replace(
        RegExp(r'^(\d+) / (\d+) durağa harcama girildi\.$'),
        (m) => 'Spending added to ${m[1]} / ${m[2]} stops.',
      ) ??
      replace(
        RegExp(r'^(\d+) / (\d+) durak · (.+)$'),
        (m) => '${m[1]} / ${m[2]} stops · ${translate(m[3]!)}',
      ) ??
      replace(
        RegExp(r'^(\d+) gün · (\d+) gece$'),
        (m) => '${m[1]} days · ${m[2]} nights',
      ) ??
      replace(
        RegExp(r'^(\d+) gün · (\d+) kişi$'),
        (m) => '${m[1]} days · ${m[2]} people',
      ) ??
      replace(RegExp(r'^(\d+) kişi$'), (m) => '${m[1]} people') ??
      replace(
        RegExp(r'^(\d+)/(\d+) durak tamamlandı$'),
        (m) => '${m[1]}/${m[2]} stops completed',
      ) ??
      replace(
        RegExp(r'^(\d+)\. Gün(?:\s*·\s*(.+))?$'),
        (m) => 'Day ${m[1]}${m[2] == null ? '' : ' · ${m[2]}'}',
      ) ??
      replace(
        RegExp(r'^(\d+) gün · (\d+) durak(?: · (.+))?$'),
        (m) =>
            '${m[1]} days · ${m[2]} stops${m[3] == null ? '' : ' · ${m[3]}'}',
      ) ??
      replace(RegExp(r'^(\d+) plan$'), (m) => '${m[1]} plans') ??
      replace(
        RegExp(r'^(.+) harcandı · (.+)$'),
        (m) => '${m[1]} spent · ${translate(m[2]!)}',
      ) ??
      replace(
        RegExp(r'^(\d+) paylaşılan plan · (\d+) farklı şehir$'),
        (m) => '${m[1]} shared plans · ${m[2]} different cities',
      ) ??
      replace(RegExp(r'^(.+) tahmini$'), (m) => '${m[1]} estimated') ??
      replace(RegExp(r'^(\d+) durak$'), (m) => '${m[1]} stops') ??
      replace(
        RegExp(
          r'^(.+@.+) adresine gönderilen bağlantıya dokun\. Ardından buraya dönüp kontrol et\.$',
        ),
        (m) => 'Tap the link sent to ${m[1]}. Then return here and check.',
      ) ??
      replace(
        RegExp(r'^Abonelik durumu: (.+)$'),
        (m) => 'Subscription status: ${translate(m[1]!)}',
      ) ??
      replace(
        RegExp(r'^Adım (\d+) / (\d+)$'),
        (m) => 'Step ${m[1]} / ${m[2]}',
      ) ??
      replace(
        RegExp(r'^Bu ay oluşturulan plan: (\d+)$'),
        (m) => 'Plans created this month: ${m[1]}',
      ) ??
      replace(RegExp(r'^Dönem sonu: (.+)$'), (m) => 'Period end: ${m[1]}') ??
      replace(RegExp(r'^Fotoğraf: (.+)$'), (m) => 'Photo: ${m[1]}') ??
      replace(
        RegExp(r'^Geçen süre: (\d+) sn$'),
        (m) => 'Elapsed: ${m[1]} sec',
      ) ??
      replace(RegExp(r'^Merhaba, (.+)!$'), (m) => 'Hello, ${m[1]}!') ??
      replace(RegExp(r'^Notun: (.+)$'), (m) => 'Your note: ${m[1]}') ??
      replace(RegExp(r'^Sonraki durak: (.+)$'), (m) => 'Next stop: ${m[1]}') ??
      replace(
        RegExp(r'^Tahmini toplam · (.+)$'),
        (m) => 'Estimated total · ${m[1]}',
      ) ??
      replace(RegExp(r'^Tahmini (.+)$'), (m) => 'Estimated ${m[1]}') ??
      replace(
        RegExp(r'^Tüm planların \((\d+)\)$'),
        (m) => 'All your plans (${m[1]})',
      ) ??
      replace(
        RegExp(r'^Yolculuğuna (\d+) gün kaldı$'),
        (m) => '${m[1]} days until your journey',
      ) ??
      replace(
        RegExp(r'^★ ([\d.,]+) · (\d+) değerlendirme$'),
        (m) => '★ ${m[1]} · ${m[2]} reviews',
      ) ??
      replace(RegExp(r'^(.+) nasıl olur\?$'), (m) => 'How about ${m[1]}?') ??
      replace(
        RegExp(r'^(.+) için tercihlerine uygun günlük rotan hazırlanıyor\.$'),
        (m) => 'Preparing a daily route for ${m[1]} based on your preferences.',
      ) ??
      replace(
        RegExp(r'^(.+) için plan oluştur$'),
        (m) => 'Create a plan for ${m[1]}',
      ) ??
      replace(
        RegExp(r'^(.+) seyahatin (\d+) gün sonra$'),
        (m) => 'Your trip to ${m[1]} is in ${m[2]} days',
      ) ??
      replace(
        RegExp(
          r'^(.+) yolculuğun için biletlerini, belgelerini ve rezervasyonlarını kontrol et\.$',
        ),
        (m) =>
            'Check your tickets, documents and reservations for your trip to ${m[1]}.',
      ) ??
      replace(
        RegExp(
          r'^(.+) için resmi ziyaret ve bilet koşullarını kontrol et\. Bu, mekan adına göre bir hatırlatmadır; rezervasyon zorunluluğu doğrulanmış değildir\.$',
        ),
        (m) =>
            'Check official visiting and ticket requirements for ${m[1]}. This reminder is based on the place name; a reservation requirement has not been verified.',
      ) ??
      replace(
        RegExp(r'^Harcama takibi · %(\d+)$'),
        (m) => 'Spending tracker · ${m[1]}%',
      ) ??
      replace(
        RegExp(r'^(.+): (.+) harcama / (.+) tahmini plan maliyeti\.$'),
        (m) => '${m[1]}: ${m[2]} spent / ${m[3]} estimated plan cost.',
      ) ??
      replace(
        RegExp(r'^(.+): (.+) harcama / (.+) ayrılan bütçe\.$'),
        (m) => '${m[1]}: ${m[2]} spent / ${m[3]} allocated budget.',
      ) ??
      replace(
        RegExp(
          r'^(Gök gürültülü hava|Kar yağışı|Yağışlı hava|Sisli hava|Açık hava|Güncel hava) · (.+)$',
        ),
        (m) => '${translate(m[1]!)} · ${m[2]}',
      ) ??
      replace(
        RegExp(
          r'^(.+) yakınındaki rota noktasının güncel hava bilgisi\. Gelecekteki seyahat gününün tahmini değildir\. Kaynak: Open-Meteo · (.+)$',
        ),
        (m) =>
            'Current weather near a route point in ${m[1]}. This is not a forecast for the future travel date. Source: Open-Meteo · ${m[2]}',
      ) ??
      _translateDateWords(source);
}

String _translateDateWords(String source) {
  var result = source;
  const words = <String, String>{
    'Pazartesi': 'Monday',
    'Çarşamba': 'Wednesday',
    'Perşembe': 'Thursday',
    'Cumartesi': 'Saturday',
    'Haziran': 'June',
    'Temmuz': 'July',
    'Ağustos': 'August',
    'Eylül': 'September',
    'Ekim': 'October',
    'Kasım': 'November',
    'Aralık': 'December',
    'Ocak': 'January',
    'Şubat': 'February',
    'Mart': 'March',
    'Nisan': 'April',
    'Mayıs': 'May',
    'Salı': 'Tuesday',
    'Cuma': 'Friday',
    'Pazar': 'Sunday',
  };
  for (final entry in words.entries) {
    result = result.replaceAll(entry.key, entry.value);
  }
  return result;
}
