export function searchCities(query: string, limit = 8): CityOption[] {
  if (!query || query.trim().length < 1) return [];
  const q = query.toLowerCase().trim();
  const results: CityOption[] = [];
  const startsWith: CityOption[] = [];
  const contains: CityOption[] = [];

  for (const c of CITIES) {
    const cityLower = c.city.toLowerCase();
    if (cityLower.startsWith(q)) startsWith.push(c);
    else if (cityLower.includes(q)) contains.push(c);
    if (startsWith.length + contains.length >= limit * 2) break;
  }

  results.push(...startsWith, ...contains);
  return results.slice(0, limit);
}
